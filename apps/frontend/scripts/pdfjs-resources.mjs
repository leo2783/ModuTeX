import { readdir, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const pdfRoot = path.dirname(require.resolve('pdfjs-dist/package.json'));
export async function pdfResourceManifest() {
 const imports = [], groups = [];
 for (const [kind, directory, pattern] of [['cMapUrl','cmaps',/\.bcmap$/], ['standardFontDataUrl','standard_fonts',/\.(pfb|ttf)$/], ['wasmUrl','wasm',/\.wasm$/]]) {
  const entries = [];
  for (const filename of (await readdir(path.join(pdfRoot, directory))).filter(name => pattern.test(name)).sort()) {
   const identifier = `resource${imports.length}`;
   imports.push(`import ${identifier} from ${JSON.stringify(`pdfjs-dist/${directory}/${filename}?url&no-inline`)};`);
   entries.push(`[${JSON.stringify(filename)}, ${identifier}]`);
  }
  groups.push(`${kind}: new Map([${entries.join(',\n')}])`);
 }
 return '// Generated by scripts/pdfjs-resources.mjs from the pinned pdfjs-dist package.\n' + imports.join('\n') + '\nexport const resources: Record<string, ReadonlyMap<string, string>> = {\n' + groups.join(',\n') + '\n};\n';
}
if (process.argv.includes('--write')) await writeFile(fileURLToPath(new URL('../src/features/pdf/resources.generated.ts', import.meta.url)), await pdfResourceManifest());
